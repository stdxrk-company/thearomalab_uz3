export function noteName(note: string, lang: Lang): string {
  return lang === 'ru' ? note : (NOTES[note]?.[lang] ?? note)
}

/** Every name of a note — used so search finds «уд», «ud» and «oud» alike. */
export function noteAliases(note: string): string[] {
  const t = NOTES[note]
  return t ? [note, t.uz, t.en] : [note]
}
